import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { renderToolchainSteps, validateCompatibilityMatrix } from "./render-workflow.mjs";

const defaultRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const contractPath = "contracts/browser-compatibility.json";

export class BrowserCompatibilityError extends Error {}

export function validateBrowserCompatibility(contract, matrix) {
  const core = validateCompatibilityMatrix(matrix);
  if (contract?.schemaVersion !== 1 || contract?.version !== 1 ||
      contract?.format !== "eliscript-browser-compatibility" ||
      contract?.workflow !== ".github/workflows/browser-compatibility.yml") {
    throw new BrowserCompatibilityError("invalid browser compatibility contract");
  }
  if (JSON.stringify(contract.browserEngines) !== JSON.stringify(["chromium", "firefox", "webkit"])) {
    throw new BrowserCompatibilityError("browserEngines must be chromium, firefox, webkit in that order");
  }
  if (contract.testCommand !== "bun test tests/direct-wasm-backend.test.mjs") {
    throw new BrowserCompatibilityError("testCommand must run the complete direct WASM backend suite");
  }
  const action = contract.artifactAction;
  if (action?.repository !== "actions/upload-artifact" ||
      !/^[0-9a-f]{40}$/.test(action?.revision ?? "") ||
      !/^v\d+(?:\.\d+){0,2}$/.test(action?.label ?? "")) {
    throw new BrowserCompatibilityError("artifactAction must pin actions/upload-artifact to a full commit SHA");
  }
  return { core, jobs: core.systems.length * contract.browserEngines.length };
}

export function renderBrowserWorkflow(contract, matrix) {
  const { core } = validateBrowserCompatibility(contract, matrix);
  const rows = core.systems.flatMap(system => contract.browserEngines.map(browser =>
    `          - name: ${system.id}-${browser}\n` +
    `            os: ${system.runner}\n` +
    `            architecture: ${system.architecture}\n` +
    `            emacs: "${core.emacsVersions.at(-1)}"\n` +
    `            browser: ${browser}`)).join("\n");
  return `# Generated by tools/ci/render-browser-workflow.mjs; do not edit.\n` +
    `name: Browser compatibility\n\n` +
    `on:\n  push:\n    branches: [master]\n  pull_request:\n  workflow_dispatch:\n\n` +
    `permissions:\n  contents: read\n\n` +
    `concurrency:\n  group: browsers-\${{ github.workflow }}-\${{ github.ref }}\n  cancel-in-progress: true\n\n` +
    `jobs:\n  browser:\n    name: \${{ matrix.name }}\n    runs-on: \${{ matrix.os }}\n` +
    `    timeout-minutes: 10\n    strategy:\n      fail-fast: false\n      matrix:\n        include:\n${rows}\n` +
    `    steps:\n` + renderToolchainSteps(matrix) +
    `      - name: Install locked dependencies\n        run: bun install --frozen-lockfile\n` +
    `      - name: Install selected browser\n        run: bun node_modules/playwright-core/cli.js install --with-deps "\${{ matrix.browser }}"\n` +
    `      - name: Run complete backend differential suite\n        shell: bash\n` +
    `        env:\n          ELISCRIPT_TEST_BROWSER: \${{ matrix.browser }}\n          DEBUG: pw:browser\n` +
    `        run: |\n          set -o pipefail\n          mkdir -p "$RUNNER_TEMP/eliscript-browser-ci"\n` +
    `          ${contract.testCommand} 2>&1 | tee "$RUNNER_TEMP/eliscript-browser-ci/tests.log"\n` +
    `      - name: Preserve browser test evidence\n        if: always()\n` +
    `        uses: ${contract.artifactAction.repository}@${contract.artifactAction.revision} # ${contract.artifactAction.label}\n` +
    `        with:\n          name: browser-\${{ matrix.name }}-\${{ github.sha }}\n` +
    `          path: \${{ runner.temp }}/eliscript-browser-ci/\n          if-no-files-found: warn\n`;
}

export async function checkBrowserCompatibilityWorkflow(options = {}) {
  const root = options.root ?? defaultRoot;
  const contract = options.contract ?? JSON.parse(await readFile(path.join(root, contractPath), "utf8"));
  const matrix = options.matrix ?? JSON.parse(await readFile(path.join(root, "contracts/compatibility-matrix.json"), "utf8"));
  const { jobs } = validateBrowserCompatibility(contract, matrix);
  const actual = options.workflowText ?? await readFile(path.join(root, contract.workflow), "utf8");
  if (actual !== renderBrowserWorkflow(contract, matrix)) {
    throw new BrowserCompatibilityError("browser workflow differs from its contracts; run the renderer with --write");
  }
  return { workflow: contract.workflow, jobs, browserEngines: contract.browserEngines };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const contract = JSON.parse(await readFile(path.join(defaultRoot, contractPath), "utf8"));
    const matrix = JSON.parse(await readFile(path.join(defaultRoot, "contracts/compatibility-matrix.json"), "utf8"));
    if (process.argv.includes("--write")) {
      await writeFile(path.join(defaultRoot, contract.workflow), renderBrowserWorkflow(contract, matrix));
    }
    console.log(JSON.stringify(await checkBrowserCompatibilityWorkflow(), null, 2));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
